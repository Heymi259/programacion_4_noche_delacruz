fun main() {

    val sociosActuales = 100
    val nuevosSocios = 20

    println("=== NOVAFIT ===")

    println("Suma")
    println("$sociosActuales + $nuevosSocios = ${sociosActuales + nuevosSocios}")

    println("Resta")
    println("$sociosActuales - $nuevosSocios = ${sociosActuales - nuevosSocios}")

    println("Multiplicación")
    println("$sociosActuales * $nuevosSocios = ${sociosActuales * nuevosSocios}")

    println("División")
    println("$sociosActuales / $nuevosSocios = ${sociosActuales / nuevosSocios}")
}